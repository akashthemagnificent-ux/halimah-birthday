import fs from 'node:fs';
const base = '/home/vibex/halimah-birthday';
const html = fs.readFileSync(base + '/index.html', 'utf8');
const css = fs.readFileSync(base + '/sections/finale.css', 'utf8');
const js = fs.readFileSync(base + '/sections/finale.js', 'utf8');
let fails = 0;
const check = (label, cond, detail = '') => { if (!cond) fails++; console.log(`[${cond ? 'PASS' : 'FAIL'}] ${label}${detail ? ' — ' + detail : ''}`); };
check('finale.css linked', html.includes('sections/finale.css'));
check('finale.js wired', html.includes('sections/finale.js'));
check('finale anchor present', html.includes('id="finale"'));
check('print CSS exists', /@media\s+print/.test(css));
check('print isolates letter', css.includes('body *') && css.includes('visibility'));
check('owner slots >= 3', (html.match(/\[OWNER:/g) || []).length >= 3, 'found ' + (html.match(/\[OWNER:/g) || []).length);
check('slot spider-line', html.includes('data-owner-slot="spider-line"'));
check('slot signature', html.includes('data-owner-slot="signature"'));
check('slot ps', html.includes('data-owner-slot="ps"'));
check('signoff carries its slot', /finale__signoff[\s\S]{0,400}\[OWNER:/.test(html));
check('star-map download wired', html.includes('assets/keepsakes/star-map-card.svg'));
check('gallery link wired', html.includes('href="#album"'));
check('story link wired', html.includes('href="#story"'));
check('letter in plain HTML', html.includes('My Halimah') && html.includes('Happy birthday, good girl'));
check('sealed state is JS-only', css.includes('html.js-finale'));
check('letter never display:none outside print', !/\.finale__letter\s*\{[^}]*display:\s*none/.test(css.split('@media print')[0]));
check('unfold uses motion tokens', css.includes('var(--duration-slow)') && css.includes('var(--ease-out)'));
check('no hardcoded hex outside print', ![...css.split('@media print')[0].matchAll(/#[0-9a-fA-F]{3,8}/g)].length);
check('star-map card file exists', fs.existsSync(base + '/assets/keepsakes/star-map-card.svg'));
check('devotion: journey line', html.toLowerCase().includes('throughout your journey,'));
check('devotion: gets better', html.toLowerCase().includes('it gets better, a lot better trust me'));
check('devotion: here-for-you-now', html.toLowerCase().includes('yes i am here for you now'));
check('devotion: if-everyone-leaves', html.toLowerCase().includes('if everyone leaves, i am here for you'));
check('devotion: proud of you', html.toLowerCase().includes('i love you so much and i am proud of you'));
check('devotion: vow', html.includes('IN THE END YOU'));
check('sources cited', html.includes('dms-6.txt:951-953') && html.includes('dms-10.txt:213,218,221') && html.includes('dms-12.txt:2639-2640'));
console.log(fails === 0 ? 'ACCEPTANCE: ALL PASS' : 'ACCEPTANCE: ' + fails + ' FAILURES');
process.exit(fails ? 1 : 0);
